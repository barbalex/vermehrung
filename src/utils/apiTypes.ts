/** error thrown by apiClient for 4xx/5xx PostgREST responses */
export class ApiError extends Error {
  status?: number
  code?: string
  details?: unknown
}

/** row shape travelling through the sync and watermelon paths, generically */
export type Row = { id: string } & Record<string, unknown>

/**
 * shape returned by the PostgREST rpc `sync`: the rows changed per table
 * since the passed watermarks, plus the server watermark. Row types are
 * generated by kanel from the database schema (src/models).
 */
export interface SyncResult {
  synced_at: number
  ae_art?: AeArt[]
  art?: Art[]
  art_file?: ArtFile[]
  art_qk?: ArtQk[]
  av?: Av[]
  bedarf?: Bedarf[]
  garten?: Garten[]
  garten_file?: GartenFile[]
  gv?: Gv[]
  herkunft?: Herkunft[]
  herkunft_file?: HerkunftFile[]
  kultur?: Kultur[]
  kultur_file?: KulturFile[]
  kultur_option?: KulturOption[]
  kultur_qk?: KulturQk[]
  lieferung?: Lieferung[]
  lieferung_file?: LieferungFile[]
  person?: Person[]
  person_file?: PersonFile[]
  person_option?: PersonOption[]
  sammel_lieferung?: SammelLieferung[]
  sammlung?: Sammlung[]
  sammlung_file?: SammlungFile[]
  teilkultur?: Teilkultur[]
  teilzaehlung?: Teilzaehlung[]
  user_role?: UserRole[]
  zaehlung?: Zaehlung[]
}

/** the minimal api surface the app talks to PostgREST with */
export interface ApiClient {
  request: (
    method: string,
    path: string,
    options?: { body?: unknown; prefer?: string },
  ) => Promise<unknown>
  get: (path: string) => Promise<unknown>
  post: <T = unknown>(
    path: string,
    body?: unknown,
    prefer?: string,
  ) => Promise<T>
  patch: <T = unknown>(
    path: string,
    body?: unknown,
    prefer?: string,
  ) => Promise<T>
  delete: (path: string, prefer?: string) => Promise<unknown>
}
